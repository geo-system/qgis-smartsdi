    def read_data_from_file(self,file):
        """
        Reads key-label pairs from a CSV file.
        """
        filepath = self.plugin_dir+"/"+file+".list"
        data = {}
        try:
            with open(filepath, 'r', encoding='utf-8') as f:
                reader = csv.DictReader(f, fieldnames=['key','value'])
                for row in reader:
                    data[row['key']]=row['value']
        except FileNotFoundError:
            QgsMessageLog.logMessage(f"Nie znaleziono pliku {filepath}", 'SmartSDI', Qgis.MessageLevel.Critical)
        except Exception as e:
            QgsMessageLog.logMessage(f"Bład czytania pliku {e}", 'SmartSDI', Qgis.MessageLevel.Critical)
        return data
        
